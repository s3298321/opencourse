import { expect, test } from '@playwright/test'

test('lesson math and highlighted code render under the production CSP, including after reload', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => {
    if (message.type() === 'error' && /Content Security Policy|inline style/i.test(message.text())) errors.push(message.text())
  })
  await page.goto('/signin')
  await page.getByLabel('Email or username').fill('grace')
  await page.getByLabel('Password', { exact: true }).fill('correct horse battery')
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('button', { name: /grace/ })).toBeVisible()
  await page.goto('/')
  await page.getByRole('link', { name: /The OpenCourse example course/ }).click()
  const description = page.locator('.course-section').filter({ has: page.getByRole('heading', { name: 'About this course' }) })
  await expect(description.locator('.course-inline-formula annotation')).toHaveText('T')
  await expect(description.locator('math[display="block"] mfrac')).toBeVisible()
  await expect(page.locator('.prereqs li math annotation')).toHaveText('T')
  await page.getByRole('button', { name: 'Add to library' }).click()
  await expect(page).toHaveURL(/\/learning\/courses\//)
  await expect(page.locator('.learning-course-description math[display="block"] mfrac')).toBeVisible()
  await expect(page.locator('.course-prerequisites li math annotation')).toHaveText('T')
  await page.getByRole('link', { name: 'Start course', exact: true }).click()
  await expect(page).toHaveURL(/\/learn\/course\//)
  const response = await page.reload()
  expect(response?.headers()['content-security-policy']).toContain("style-src 'self'")
  const reader = page.locator('.reader-content')
  await expect(reader.getByRole('heading', { name: 'Hello, Python', exact: true })).toHaveCount(1)
  await expect(reader.locator('.lesson-title + .lesson-objectives li')).toHaveCount(3)
  await expect(reader.locator('.lesson-objectives li math annotation')).toHaveText('c_{n+1}')
  const inline = reader.locator('.lesson-prose p .course-inline-formula math').first()
  await expect(inline).toBeVisible()
  await expect(inline.locator('annotation')).toHaveText('c_n')
  // Check the equation's position against the adjacent prose on the rendered line.
  expect(await inline.evaluate(math => {
    const range = math.ownerDocument.createRange()
    range.selectNodeContents(math.closest('.course-inline-formula')!.previousSibling!)
    const previous = [...range.getClientRects()].at(-1)!
    const equation = math.getBoundingClientRect()
    return previous.right <= equation.left + 1 && previous.top < equation.bottom && equation.top < previous.bottom
  })).toBe(true)
  const formula = page.locator('.reader-content math[display="block"]')
  await expect(formula).toBeVisible()
  await expect(formula.locator('msub')).toHaveCount(2)
  await expect(formula.locator('annotation')).toHaveText('c_{n+1} = c_n + 1')
  for (const [part, expected] of [['msub mrow', 'n+1'], ['semantics > mrow', 'c_{n+1} = c_n + 1']]) {
    await formula.locator(part).first().evaluate(node => {
      const range = node.ownerDocument.createRange()
      range.selectNodeContents(node)
      const selection = node.ownerDocument.getSelection()!
      selection.removeAllRanges()
      selection.addRange(range)
    })
    await page.getByRole('button', { name: 'Ask about this', exact: true }).click()
    const chat = page.getByRole('complementary', { name: 'Reading chat' })
    expect(await chat.locator('.sidechat-quote blockquote').textContent()).toBe(expected)
    await chat.getByRole('button', { name: 'Remove selected passage' }).click()
    await chat.getByRole('button', { name: 'Close chat' }).click()
  }
  const quiz = page.locator('form.learning-card').filter({ hasText: 'If the counter shows' })
  await expect(quiz.locator('.oc-prose math annotation')).toHaveText('c_n = 3')
  await expect(quiz.locator('label math annotation')).toHaveText(['c_{n+2} = 4', 'c_{n+2} = 5'])
  const explanation = quiz.locator('.explanation')
  await expect(explanation).toHaveCount(0)
  await quiz.locator('label').first().click()
  await quiz.getByRole('button', { name: 'Check answer' }).click()
  await expect(quiz.getByText('Try again', { exact: true })).toBeVisible()
  await expect(explanation.locator('.course-inline-formula annotation')).toHaveText('c_n = 3')
  await expect(explanation.locator('math[display="block"] annotation')).toHaveText('c_{n+2} = 3 + 1 + 1 = 5')
  const answer = quiz.locator('label').last()
  await answer.locator('math').click()
  await expect(answer.getByRole('radio')).toBeChecked()
  await quiz.getByRole('button', { name: 'Check answer' }).click()
  await expect(quiz.getByText('Correct', { exact: true })).toBeVisible()
  await expect(explanation.locator('math')).toHaveCount(2)
  await page.getByRole('navigation', { name: 'Course outline' }).getByRole('button', { name: /Variables and types/ }).click()
  const code = page.locator('.lesson-prose pre.syntax-highlight')
  await expect(code).toBeVisible()
  const string = code.locator('span').filter({ hasText: '"Ada"' })
  await expect(string).toHaveCSS('color', 'rgb(158, 203, 255)')
  await expect(code.locator('span').filter({ hasText: /^36$/ })).toHaveCSS('color', 'rgb(121, 184, 255)')
  await expect(code.locator('[style]')).toHaveCount(0)
  await expect(code).toHaveText('name = "Ada"\nage = 36\n')
  await page.reload()
  await expect(string).toHaveCSS('color', 'rgb(158, 203, 255)')
  await code.screenshot({ path: '/tmp/opencourse-web-syntax-highlighting.png' })
  await page.getByRole('navigation', { name: 'Course outline' }).getByRole('button', { name: /Two ways to check Python exercises/ }).click()
  const exercise = page.locator('.web-exercise').filter({ hasText: 'A function, checked by a test file' })
  await expect(exercise.locator('.prompt math annotation')).toHaveText(['3n', 'n'])
  await expect(exercise.locator('.verify .course-inline-formula annotation')).toHaveText('n = 2')
  await expect(exercise.locator('.verify math[display="block"] annotation')).toHaveText(String.raw`3 \times 2 = 6`)
  const hints = exercise.locator('details').filter({ hasText: 'Hints (1)' })
  await expect(hints.locator('math')).toHaveCount(0)
  await hints.locator('summary').click()
  await expect(hints.locator('math[display="block"] annotation')).toHaveText('3n = n + n + n')
  await exercise.getByRole('button', { name: 'Start exercise' }).click()
  const brief = page.locator('.exercise-brief')
  await expect(brief.locator('.prompt math annotation')).toHaveText(['3n', 'n'])
  await expect(brief.locator('.verify .course-inline-formula annotation')).toHaveText('n = 2')
  await expect(brief.locator('.verify math[display="block"] annotation')).toHaveText(String.raw`3 \times 2 = 6`)
  await brief.locator('summary').filter({ hasText: 'Hints' }).click()
  await expect(brief.locator('li math annotation')).toHaveText('3n = n + n + n')
  await page.getByRole('navigation', { name: 'Course outline' }).getByRole('button', { name: /Project workspace/ }).click()
  await expect(reader.getByRole('heading', { name: 'What you will practice' })).toBeVisible()
  await expect(reader.locator('.lesson-objectives li math annotation')).toHaveText(['T', 't_1 + t_2 + t_3 = T'])
  const definition = reader.locator('.project-definition')
  await expect(definition.locator('.course-inline-formula annotation')).toHaveText('T')
  await expect(definition.locator('math[display="block"] mfrac')).toBeVisible()
  await expect(reader.locator('.project-requirements math annotation')).toHaveText('t_i')
  const outline = reader.locator('.project-deliverables .oc-panel').first()
  await expect(outline.locator('h3 math annotation')).toHaveText('T')
  await expect(outline.locator('.oc-prose p .course-inline-formula annotation')).toHaveText('T')
  await expect(outline.locator('li math[display="block"] annotation')).toHaveText('t_1 + t_2 + t_3 = T')
  await expect(outline.locator('.project-paths code')).toHaveText('OUTLINE.md')
  expect(errors).toEqual([])
})
